-- ---------------------------------------------------------------------
-- 性格特性（5つ）
-- score: 図にあったカラム。用途未定（正規化用の最大値などに使う想定）
-- ---------------------------------------------------------------------
CREATE TABLE personality (
    personality_id INT          PRIMARY KEY,
    name           VARCHAR(20)  NOT NULL,
    score          INT
);

-- ---------------------------------------------------------------------
-- 質問
-- type    : 採点のしかた  NORMAL=通常 / FAKE=採点しない / FRENEMY=フレネミー質問
-- critical: TRUE なら「とても当てはまる」でクリティカル吉嵜発動
-- personality_id: 通常質問のカテゴリ。特殊質問は NULL
-- ---------------------------------------------------------------------
CREATE TABLE question (
    question_id    INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question       VARCHAR(255) NOT NULL,
    critical       BOOLEAN      NOT NULL DEFAULT FALSE,
    type           VARCHAR(20)  NOT NULL DEFAULT 'NORMAL',
    personality_id INT,
    CONSTRAINT ck_question_type CHECK (type IN ('NORMAL', 'FAKE', 'FRENEMY')),
    CONSTRAINT fk_question_personality FOREIGN KEY (personality_id) REFERENCES personality(personality_id)
);

-- ---------------------------------------------------------------------
-- 回答の選択肢（4段階）
-- ---------------------------------------------------------------------
CREATE TABLE answer_select (
    choice_id INT         PRIMARY KEY,
    label     VARCHAR(30) NOT NULL
);

-- ---------------------------------------------------------------------
-- 質問×選択肢ごとの点数
-- 1問に4つの選択肢があるので、主キーは (question_id, choice_id) の複合キー
-- 逆転質問（「一人が好き」など）はここで符号を反転させる
-- ---------------------------------------------------------------------
CREATE TABLE scoring (
    question_id INT NOT NULL,
    choice_id   INT NOT NULL,
    score       INT NOT NULL,
    PRIMARY KEY (question_id, choice_id),
    CONSTRAINT fk_scoring_question FOREIGN KEY (question_id) REFERENCES question(question_id),
    CONSTRAINT fk_scoring_choice   FOREIGN KEY (choice_id)   REFERENCES answer_select(choice_id)
);

-- ---------------------------------------------------------------------
-- 固定スコア（「自分をフレネミーだと思いますか」で「とても当てはまる」を選ぶと
-- 5特性のスコアがこの値になる）
-- ---------------------------------------------------------------------
CREATE TABLE fixed_score (
    question_id    INT NOT NULL,
    choice_id      INT NOT NULL,
    personality_id INT NOT NULL,
    score          INT NOT NULL,
    PRIMARY KEY (question_id, choice_id, personality_id),
    CONSTRAINT fk_fixed_question    FOREIGN KEY (question_id)    REFERENCES question(question_id),
    CONSTRAINT fk_fixed_choice      FOREIGN KEY (choice_id)      REFERENCES answer_select(choice_id),
    CONSTRAINT fk_fixed_personality FOREIGN KEY (personality_id) REFERENCES personality(personality_id)
);

-- ---------------------------------------------------------------------
-- 役職
-- ---------------------------------------------------------------------
CREATE TABLE role (
    id          INT           PRIMARY KEY,
    name        VARCHAR(30)   NOT NULL,
    description VARCHAR(1000),
    is_black    BOOLEAN       NOT NULL DEFAULT FALSE
);

-- ---------------------------------------------------------------------
-- 役職ごとの閾値（役職×特性）
-- 正規化スコア(-30〜+30)が min_score〜max_score に入っていれば一致1つ
-- ---------------------------------------------------------------------
CREATE TABLE role_threshold (
    role_id        INT NOT NULL,
    personality_id INT NOT NULL,
    min_score      INT NOT NULL,
    max_score      INT NOT NULL,
    PRIMARY KEY (role_id, personality_id),
    CONSTRAINT fk_threshold_role        FOREIGN KEY (role_id)        REFERENCES role(id),
    CONSTRAINT fk_threshold_personality FOREIGN KEY (personality_id) REFERENCES personality(personality_id),
    CONSTRAINT ck_threshold_range CHECK (min_score <= max_score)
);

-- ---------------------------------------------------------------------
-- 画像・おすすめアイテム・アカウント
-- image / item は役職ごとに持つ（role_id）。
-- 結果を保存するときに、その役職の中からランダムに1件選んで result に入れる
-- ---------------------------------------------------------------------
CREATE TABLE image (
    image_id INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id  INT          NOT NULL,
    path     VARCHAR(255) NOT NULL,
    CONSTRAINT fk_image_role FOREIGN KEY (role_id) REFERENCES role(id)
);

CREATE TABLE item (
    item_id INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id INT          NOT NULL,
    name    VARCHAR(100) NOT NULL,
    CONSTRAINT fk_item_role FOREIGN KEY (role_id) REFERENCES role(id)
);

-- password はハッシュ化した値を入れる（平文で保存しない）
-- 形式: PBKDF2WithHmacSHA256 の "salt:hash"（どちらもBase64）。model.PasswordUtil 参照
CREATE TABLE account (
    user_id  INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(50)  NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

-- ---------------------------------------------------------------------
-- 診断結果
-- 設計書の「役職IDと5特性の各スコア、診断日時」も保存するため列を追加
-- user_id は未ログインなら NULL
-- CounterDAO の SELECT COUNT(*) FROM result で診断人数を数える
-- ---------------------------------------------------------------------
CREATE TABLE result (
    result_id           INT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id            INT,
    role_id             INT       NOT NULL,
    item_id             INT,
    user_id             INT,
    extraversion        INT,       -- 外向性
    agreeableness       INT,       -- 協調性
    conscientiousness   INT,       -- 誠実性
    emotional_stability INT,       -- 情緒安定性
    openness            INT,       -- 開放性
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_result_image FOREIGN KEY (image_id) REFERENCES image(image_id),
    CONSTRAINT fk_result_role  FOREIGN KEY (role_id)  REFERENCES role(id),
    CONSTRAINT fk_result_item  FOREIGN KEY (item_id)  REFERENCES item(item_id),
    CONSTRAINT fk_result_user  FOREIGN KEY (user_id)  REFERENCES account(user_id)
);


